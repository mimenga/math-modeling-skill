%% ============================================================
% 非线性优化_fmincon.m
% 用途：带约束非线性规划（无约束用 fminunc/fminsearch）
% 依赖：Optimization Toolbox
% ============================================================
clear; clc;

%% 1. 无约束非线性优化 fminunc
% 例：min f = x1^2 + x2^2 + x1*x2 - 2x1 - 3x2
fun1 = @(x) x(1)^2 + x(2)^2 + x(1)*x(2) - 2*x(1) - 3*x(2);
x0 = [1; 1];
[x, fval] = fminunc(fun1, x0);
fprintf('fminunc 最优解: (%.4f, %.4f), 最优值: %.4f\n', x(1), x(2), fval);

%% 2. 有约束非线性优化 fmincon
% 例：min f = x1^2 + x2^2
%     s.t. x1 + 2x2 >= 3  （写为 -x1 - 2x2 <= -3）
%          0 <= x1 <= 4, 0 <= x2 <= 4
fun2 = @(x) x(1)^2 + x(2)^2;
A = [-1 -2];                     % 不等式约束 A*x <= b
b = [-3];
lb = [0; 0]; ub = [4; 4];
x0 = [1; 1];
[x, fval] = fmincon(fun2, x0, A, b, [], [], lb, ub);
fprintf('fmincon 最优解: (%.4f, %.4f), 最优值: %.4f\n', x(1), x(2), fval);

%% 3. 多目标 → 加权转单目标（线性加权法）
% 例：min f1 = x1, min f2 = x2, 约束 x1 + x2 >= 1, x >= 0
% 用权重 w1=0.5, w2=0.5
w = [0.5; 0.5];
fun3 = @(x) w(1)*x(1) + w(2)*x(2);
A3 = [-1 -1]; b3 = [-1];
[x, fval] = fmincon(fun3, [0.5; 0.5], A3, b3, [], [], [0; 0], []);
fprintf('多目标加权最优解: (%.4f, %.4f)\n', x(1), x(2));

%% 4. 网格搜索（简单暴力寻优，低维用）
xx = 0:0.01:1; yy = 0:0.01:1;
[Xg, Yg] = meshgrid(xx, yy);
F = Xg.^2 + Yg.^2;               % 目标函数
[minF, idx] = min(F(:));
fprintf('网格搜索最小值: %.4f @ (%.2f, %.2f)\n', ...
    minF, Xg(idx), Yg(idx));
